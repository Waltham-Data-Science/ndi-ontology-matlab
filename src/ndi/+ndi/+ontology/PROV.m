% Location: +ndi/+ontology/PROV.m
classdef PROV < ndi.ontology
% PROV - NDI Ontology object for PROV-O, the W3C PROV Ontology (https://www.w3.org/TR/prov-o/):
%   its starting-point classes (prov:Entity, prov:Activity, prov:Agent) and
%   the relations between them, such as prov:wasDerivedFrom. The text is
%   PROV-O's prov:definition where it has one, else its rdfs:comment, taken
%   from the PROV-O file at http://www.w3.org/ns/prov-o (read 2026-10-23).
%   A term is identified as the vocabulary names it, prov:<localName>, which
%   resolves to http://www.w3.org/ns/prov#<localName>.
%
%   PROV is a W3C vocabulary, not an OBO ontology, and NDI uses a fixed few of
%   its terms, so the names and definitions are held here (as ndi.ontology.OWLTime
%   holds the OWL-Time interval relations).

    properties (Constant)
        % local name (also the rdfs:label), definition
        TERMS = { ...
                'Entity', 'An entity is a physical, digital, conceptual, or other kind of thing with some fixed aspects; entities may be real or imaginary.';
                'Activity', 'An activity is something that occurs over a period of time and acts upon or with entities; it may include consuming, processing, transforming, modifying, relocating, using, or generating entities.';
                'Agent', 'An agent is something that bears some form of responsibility for an activity taking place, for the existence of an entity, or for another agent''s activity.';
                'wasDerivedFrom', 'A derivation is a transformation of an entity into another, an update of an entity resulting in a new one, or the construction of a new entity based on a pre-existing entity.';
                'wasRevisionOf', 'A revision is a derivation that revises an entity into a revised version.';
                'wasQuotedFrom', 'An entity is derived from an original entity by copying, or ''quoting'', some or all of it.';
                'wasAttributedTo', 'Attribution is the ascribing of an entity to an agent.';
                'used', 'A prov:Entity that was used by this prov:Activity. For example, :baking prov:used :spoon, :egg, :oven .';
                'wasInformedBy', 'An activity a2 is dependent on or informed by another activity a1, by way of some unspecified entity that is generated by a1 and used by a2.';
                'wasAssociatedWith', 'An prov:Agent that had some (unspecified) responsibility for the occurrence of this prov:Activity.';
                'actedOnBehalfOf', 'An object property to express the accountability of an agent towards another agent. The subordinate agent acted on behalf of the responsible agent in an actual activity.';
                'startedAtTime', 'The time at which an activity started. See also prov:endedAtTime.';
                'endedAtTime', 'The time at which an activity ended. See also prov:startedAtTime.'};
    end

    methods
        function obj = PROV()
            % PROV - Constructor for the PROV ontology object.
        end % constructor

        function [id, name, definition, synonyms] = lookupTermOrID(obj, term_or_id_or_name)
            % LOOKUPTERMORID - Looks up a PROV term by local name.
            %
            %   [ID, NAME, DEFINITION, SYNONYMS] = lookupTermOrID(OBJ, TERM)
            %
            %   TERM is the part after the 'prov:' prefix: the local name
            %   ('wasDerivedFrom'), in any case, with or without spaces or underscores
            %   ('was derived from'). ID is always 'prov:<localName>'; NAME is the
            %   rdfs:label (the local name); SYNONYMS holds the terms IRI.
            arguments
                obj (1,1) ndi.ontology.PROV %#ok<INUSA> (the lookup interface)
                term_or_id_or_name {mustBeText}
            end
            k = ndi.ontology.PROV.find(term_or_id_or_name);
            if isempty(k)
                error('ndi:ontology:PROV:LookupFailed', ...
                    'PROV lookup failed: "%s" is not one of the PROV terms NDI holds.', ...
                    char(term_or_id_or_name));
            end
            T = ndi.ontology.PROV.TERMS;
            id = ['prov:' T{k, 1}];
            name = T{k, 1};
            definition = T{k, 2};
            synonyms = {['http://www.w3.org/ns/prov#' T{k, 1}]};
        end % function lookupTermOrID
    end % methods

    methods (Static)
        function k = find(term)
            % FIND - The row of TERMS that TERM names, or [] if none.
            %   Case, spaces and underscores do not distinguish one term
            %   from another, so 'wasDerivedFrom', 'was derived from' and
            %   'WAS_DERIVED_FROM' are the same term.
            arguments
                term {mustBeText}
            end
            T = ndi.ontology.PROV.TERMS;
            key = regexprep(lower(strtrim(char(term))), '[\s_]+', '');
            k = [];
            if isempty(key), return; end
            for r = 1:size(T, 1)
                if strcmpi(key, T{r, 1})
                    k = r;
                    return;
                end
            end
        end
    end % methods (Static)

end % classdef PROV
