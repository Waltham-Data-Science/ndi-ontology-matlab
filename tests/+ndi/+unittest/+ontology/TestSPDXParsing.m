classdef TestSPDXParsing < matlab.unittest.TestCase
    % TestSPDXParsing - Offline tests of how an SPDX License List response
    %   becomes the spdx: lookup ID, name and definition. The bodies below
    %   are cut down from https://spdx.org/licenses/CC-BY-4.0.json (one
    %   licence) and https://spdx.org/licenses/licenses.json (the list).

    properties (Constant)
        LicenseBody = [ ...
            '{"isDeprecatedLicenseId": false, "isFsfLibre": true,' newline ...
            ' "licenseText": "Creative Commons Attribution 4.0 International ...",' newline ...
            ' "name": "Creative Commons Attribution 4.0 International",' newline ...
            ' "licenseId": "CC-BY-4.0",' newline ...
            ' "seeAlso": ["https://creativecommons.org/licenses/by/4.0/legalcode"],' newline ...
            ' "isOsiApproved": false}'];

        IndexBody = [ ...
            '{"licenseListVersion": "3.27", "licenses": [' newline ...
            ' {"reference": "https://spdx.org/licenses/MIT.html", "isDeprecatedLicenseId": false,' ...
            ' "detailsUrl": "https://spdx.org/licenses/MIT.json", "referenceNumber": 1,' ...
            ' "name": "MIT License", "licenseId": "MIT",' ...
            ' "seeAlso": ["https://opensource.org/license/MIT"], "isOsiApproved": true},' newline ...
            ' {"reference": "https://spdx.org/licenses/CC0-1.0.html", "isDeprecatedLicenseId": false,' ...
            ' "detailsUrl": "https://spdx.org/licenses/CC0-1.0.json", "referenceNumber": 2,' ...
            ' "name": "Creative Commons Zero v1.0 Universal", "licenseId": "CC0-1.0",' ...
            ' "seeAlso": ["https://creativecommons.org/publicdomain/zero/1.0/legalcode"], "isOsiApproved": false},' newline ...
            ' {"reference": "https://spdx.org/licenses/GPL-2.0.html", "isDeprecatedLicenseId": true,' ...
            ' "detailsUrl": "https://spdx.org/licenses/GPL-2.0.json", "referenceNumber": 3,' ...
            ' "name": "GNU General Public License v2.0 only", "licenseId": "GPL-2.0",' ...
            ' "seeAlso": [], "isOsiApproved": true}' newline ...
            '], "releaseDate": "2025-07-01"}'];
    end

    methods (Test)

        function testLicenseFromDetailsJson(testCase)
            [id, name, definition] = ndi.ontology.SPDX.parseLicense(testCase.LicenseBody);
            testCase.verifyEqual(id, 'spdx:CC-BY-4.0');
            testCase.verifyEqual(name, 'Creative Commons Attribution 4.0 International');
            testCase.verifyEqual(definition, [ ...
                'SPDX licence CC-BY-4.0: Creative Commons Attribution 4.0 International.' ...
                ' See https://creativecommons.org/licenses/by/4.0/legalcode']);
        end

        function testIndexMatchesIdIgnoringCase(testCase)
            entry = ndi.ontology.SPDX.findInIndex(testCase.IndexBody, 'cc0-1.0');
            testCase.verifyNotEmpty(entry);
            [id, name] = ndi.ontology.SPDX.parseLicense(entry);
            testCase.verifyEqual(id, 'spdx:CC0-1.0', ...
                'The returned ID carries the canonical identifier, not the query''s case.');
            testCase.verifyEqual(name, 'Creative Commons Zero v1.0 Universal');
        end

        function testIndexMatchesFullName(testCase)
            entry = ndi.ontology.SPDX.findInIndex(testCase.IndexBody, 'mit license');
            testCase.verifyNotEmpty(entry);
            id = ndi.ontology.SPDX.parseLicense(entry);
            testCase.verifyEqual(id, 'spdx:MIT');
        end

        function testIndexMissIsEmpty(testCase)
            entry = ndi.ontology.SPDX.findInIndex(testCase.IndexBody, 'NoSuchLicence-9.9');
            testCase.verifyEmpty(entry);
        end

        function testDeprecatedAndNoSeeAlso(testCase)
            entry = ndi.ontology.SPDX.findInIndex(testCase.IndexBody, 'GPL-2.0');
            [id, ~, definition] = ndi.ontology.SPDX.parseLicense(entry);
            testCase.verifyEqual(id, 'spdx:GPL-2.0');
            testCase.verifyEqual(definition, [ ...
                'SPDX licence GPL-2.0: GNU General Public License v2.0 only.' ...
                ' This SPDX identifier is deprecated.']);
        end

        function testInvalidJsonIsAParseError(testCase)
            testCase.verifyError(@() ndi.ontology.SPDX.parseLicense('<html>not json</html>'), ...
                'ndi:ontology:SPDX:ParseError');
        end

    end % methods (Test)

end % classdef
