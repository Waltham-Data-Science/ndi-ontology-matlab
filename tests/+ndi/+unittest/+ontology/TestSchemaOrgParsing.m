classdef TestSchemaOrgParsing < matlab.unittest.TestCase
    % TestSchemaOrgParsing - Offline tests of how a schema.org response
    %   becomes the schema: lookup name and definition. schema.org returns
    %   an HTML term page even when JSON-LD is requested, with the term's
    %   JSON-LD embedded in a <script type="application/ld+json"> block; the
    %   bodies below are cut down from the pages served for isPartOf (a
    %   property: the term itself) and Person (a type: an @graph).

    methods (Test)

        function testPropertyFromHtmlPage(testCase)
            body = [ ...
                '<!DOCTYPE html><html lang="en"><head>' newline ...
                '<title>isPartOf - Schema.org Property</title>' newline ...
                '<script type="application/ld+json">' newline ...
                '{ "@context": { "rdfs": "http://www.w3.org/2000/01/rdf-schema#",' ...
                ' "schema": "https://schema.org/" },' newline ...
                '  "@id": "schema:isPartOf", "@type": "rdf:Property",' newline ...
                '  "rdfs:comment": "Indicates an item or CreativeWork that this item, or CreativeWork (in some sense), is part of.",' newline ...
                '  "rdfs:label": "isPartOf",' newline ...
                '  "schema:inverseOf": { "@id": "schema:hasPart" } }' newline ...
                '</script></head><body></body></html>'];
            [name, definition] = ndi.ontology.SchemaOrg.parseResponse(body, 'isPartOf');
            testCase.verifyEqual(name, 'isPartOf');
            testCase.verifyTrue(startsWith(definition, 'Indicates an item or CreativeWork'), ...
                'The definition is the property''s rdfs:comment.');
        end

        function testTypeFromHtmlGraph(testCase)
            body = [ ...
                '<html><head><script type="application/ld+json">' newline ...
                '{ "@context": { "schema": "https://schema.org/" }, "@graph": [' newline ...
                '  { "@id": "schema:Person", "@type": "rdfs:Class",' ...
                ' "rdfs:comment": "A person (alive, dead, undead, or fictional).",' ...
                ' "rdfs:label": "Person" },' newline ...
                '  { "@id": "schema:additionalName", "@type": "rdf:Property",' ...
                ' "rdfs:comment": "An additional name for a Person.",' ...
                ' "rdfs:label": "additionalName",' ...
                ' "schema:domainIncludes": { "@id": "schema:Person" } } ] }' newline ...
                '</script></head></html>'];
            [name, definition] = ndi.ontology.SchemaOrg.parseResponse(body, 'Person');
            testCase.verifyEqual(name, 'Person');
            testCase.verifyEqual(definition, 'A person (alive, dead, undead, or fictional).');
        end

        function testBareJsonLd(testCase)
            body = '{ "@id": "https://schema.org/Dataset", "rdfs:label": "Dataset", "rdfs:comment": "A body of structured information." }';
            [name, definition] = ndi.ontology.SchemaOrg.parseResponse(body, 'Dataset');
            testCase.verifyEqual(name, 'Dataset');
            testCase.verifyEqual(definition, 'A body of structured information.');
        end

        function testNoJsonLdFallsBackToTheTerm(testCase)
            body = '<html><body>No structured data here.</body></html>';
            [name, definition] = ndi.ontology.SchemaOrg.parseResponse(body, 'isPartOf');
            testCase.verifyEqual(name, 'isPartOf');
            testCase.verifyEqual(definition, '');
        end

    end % methods (Test)

end % classdef
