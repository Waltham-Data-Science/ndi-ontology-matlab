classdef TestInterLexWikidataParsing < matlab.unittest.TestCase
    % TestInterLexWikidataParsing - Offline tests of how an InterLex JSON-LD
    %   record and a Wikidata wbgetentities response become the lookup ID,
    %   name, definition and synonyms. The bodies below are cut down from
    %   http://uri.interlex.org/base/ilx_0739413.jsonld and
    %   https://www.wikidata.org/w/api.php?action=wbgetentities&ids=Q30
    %   (both read 2026-10-21).

    properties (Constant)
        InterLexBody = [ ...
            '{"@context": {"ILX": "http://uri.interlex.org/base/ilx_",' ...
            ' "NIFRID": "http://uri.neuinfo.org/nif/nifstd/readable/",' ...
            ' "definition": "http://purl.obolibrary.org/obo/IAO_0000115",' ...
            ' "rdfs": "http://www.w3.org/2000/01/rdf-schema#"},' newline ...
            ' "@graph": [' newline ...
            '  {"@id": "http://uri.interlex.org/base/ilx_0739413", "@type": "owl:Class",' ...
            '   "NIFRID:synonym": "behavioral approach",' ...
            '   "definition": "Study that induces and/or measures the behavior of the subject",' ...
            '   "rdfs:label": "behavioral approach",' ...
            '   "rdfs:subClassOf": {"@id": "http://uri.interlex.org/base/ilx_0770148"}},' newline ...
            '  {"@id": "http://uri.interlex.org/base/ontologies/ilx_0739413", "@type": "owl:Ontology"},' newline ...
            '  {"@id": "http://uri.interlex.org/base/ilx_0770148", "@type": "owl:Class",' ...
            '   "rdfs:label": "Experimental modalities"}' newline ...
            ' ]}'];

        WikidataBody = [ ...
            '{"entities":{"Q30":{"type":"item","id":"Q30",' ...
            '"labels":{"en":{"language":"en","value":"United States"}},' ...
            '"descriptions":{"en":{"language":"en","value":"country located primarily in North America"}},' ...
            '"aliases":{"en":[{"language":"en","value":"the States"},{"language":"en","value":"the US"}]}}},' ...
            '"success":1}'];

        WikidataMissing = '{"entities":{"Q99999999999":{"id":"Q99999999999","missing":""}},"success":1}';

        WikidataSearch = [ ...
            '{"search":[{"id":"Q458","label":"European Union"},' ...
            '{"id":"Q1","label":"European Union flag"}],"success":1}'];
    end

    methods (Test)

        function testInterLexIdForms(testCase)
            testCase.verifyEqual(ndi.ontology.InterLex.localNumber('0739413'), '0739413');
            testCase.verifyEqual(ndi.ontology.InterLex.localNumber('ilx_0739413'), '0739413');
            testCase.verifyEqual(ndi.ontology.InterLex.localNumber('ILX_0739413'), '0739413');
            testCase.verifyEmpty(ndi.ontology.InterLex.localNumber('behavior'));
        end

        function testInterLexRecord(testCase)
            [id, name, definition, synonyms] = ...
                ndi.ontology.InterLex.parseRecord(testCase.InterLexBody, '0739413');
            testCase.verifyEqual(id, 'ILX:0739413');
            testCase.verifyEqual(name, 'behavioral approach', ...
                'InterLex labels ilx_0739413 "behavioral approach"; openMINDS names it "behavior".');
            testCase.verifyEqual(definition, ...
                'Study that induces and/or measures the behavior of the subject');
            testCase.verifyEqual(synonyms, {'behavioral approach'});
        end

        function testInterLexPicksTheTermNotItsParent(testCase)
            [~, name] = ndi.ontology.InterLex.parseRecord(testCase.InterLexBody, '0770148');
            testCase.verifyEqual(name, 'Experimental modalities');
            testCase.verifyError(@() ndi.ontology.InterLex.parseRecord( ...
                testCase.InterLexBody, '0000001'), 'ndi:ontology:InterLex:TermNotFound');
        end

        function testInterLexInvalidJson(testCase)
            testCase.verifyError(@() ndi.ontology.InterLex.parseRecord('<html/>', '1'), ...
                'ndi:ontology:InterLex:ParseError');
        end

        function testWikidataEntity(testCase)
            [id, name, definition, synonyms] = ...
                ndi.ontology.Wikidata.parseEntity(testCase.WikidataBody, 'Q30');
            testCase.verifyEqual(id, 'wikidata:Q30');
            testCase.verifyEqual(name, 'United States');
            testCase.verifyEqual(definition, 'country located primarily in North America');
            testCase.verifyEqual(synonyms, {'the States', 'the US'});
        end

        function testWikidataMissing(testCase)
            testCase.verifyError(@() ndi.ontology.Wikidata.parseEntity( ...
                testCase.WikidataMissing, 'Q99999999999'), 'ndi:ontology:Wikidata:TermNotFound');
        end

        function testWikidataLabelSearchIsExact(testCase)
            testCase.verifyEqual(ndi.ontology.Wikidata.exactLabelMatch( ...
                testCase.WikidataSearch, 'european union'), 'Q458');
            testCase.verifyEmpty(ndi.ontology.Wikidata.exactLabelMatch( ...
                testCase.WikidataSearch, 'Europe'));
        end

    end % methods (Test)

end % classdef
